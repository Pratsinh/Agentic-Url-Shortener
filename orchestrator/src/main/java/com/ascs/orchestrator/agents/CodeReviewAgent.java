package com.ascs.orchestrator.agents;

import com.ascs.orchestrator.core.Agent;
import com.ascs.orchestrator.model.AgentResult;
import com.ascs.orchestrator.model.StageInput;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Code-review agent: reviews every Java file (main and test) against explicit rules and reports, per file,
 * that it was reviewed and what was found. A finding is resolved either by fixing the code or by an explicit,
 * reasoned waiver comment on the same or the preceding line: {@code review:accepted <rule id> <reason>}.
 * The report never echoes source lines, so a leaked secret is located without being repeated.
 */
public final class CodeReviewAgent implements Agent {

    public static final String OUTPUT = "code-review.md";

    public enum Severity { HIGH, MEDIUM, LOW }

    public record Rule(String id, Severity severity, String title, boolean mainOnly, Pattern pattern) {}

    public record Finding(Rule rule, String file, int line, String waiver) {
        public boolean open() { return waiver == null; }
    }

    // Patterns are assembled from fragments where needed so this file does not match its own rules.
    public static final List<Rule> RULES = List.of(
            new Rule("CR-01", Severity.HIGH, "Hard-coded secret or private key", false,
                    Pattern.compile("AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE" + " KEY-----")),
            new Rule("CR-02", Severity.HIGH, "Empty catch block swallows the error", false,
                    Pattern.compile("catch\\s*\\([^)]*\\)\\s*\\{\\s*}")),
            new Rule("CR-03", Severity.MEDIUM, "Stack trace printed instead of logged", false,
                    Pattern.compile("\\.print" + "StackTrace\\(")),
            new Rule("CR-04", Severity.MEDIUM, "Console output outside a CLI entry point", true,
                    Pattern.compile("System\\.(out|err)\\b")),
            new Rule("CR-05", Severity.LOW, "Unresolved to-do marker", false,
                    Pattern.compile("\\b(TO" + "DO|FIX" + "ME)\\b")),
            new Rule("CR-06", Severity.MEDIUM, "Predictable java.util.Random in production code", true,
                    Pattern.compile("new\\s+Random\\s*\\(")),
            new Rule("CR-07", Severity.LOW, "Public top-level type without Javadoc", true,
                    Pattern.compile("^public\\s+(?:(?:final|abstract|sealed|non-sealed|static)\\s+)*(?:class|interface|record|enum|@interface)\\s")));

    private static final Pattern WAIVER = Pattern.compile("review:accepted\\s+(CR-\\d+)\\s+(.+?)\\s*(?:\\*/)?$");
    private static final String CLI_MARKER = "public static void main(";

    private final Path projectRoot;

    public CodeReviewAgent(Path projectRoot) {
        this.projectRoot = projectRoot;
    }

    @Override
    public AgentResult execute(StageInput input) {
        List<SourceFile> files = SourceFile.scan(projectRoot, SourceFile.sourceRoots(projectRoot, "main", "test"));
        List<Finding> findings = new ArrayList<>();
        for (SourceFile f : files) findings.addAll(review(f));

        long open = findings.stream().filter(Finding::open).count();
        long blocking = findings.stream().filter(x -> x.open() && x.rule().severity() != Severity.LOW).count();
        long mainFiles = files.stream().filter(f -> !f.isTest()).count();
        long lines = files.stream().mapToLong(f -> f.lines().size()).sum();
        String verdict = blocking == 0 ? "APPROVED" : "CHANGES REQUESTED";

        StringBuilder md = new StringBuilder("# Code review\n\n")
                .append("Generated by `CodeReviewAgent`. Scope: every Java file under `src/main/java` and `src/test/java` of every module.\n\n")
                .append("- **Files reviewed:** ").append(files.size()).append(" / ").append(files.size())
                .append(" (").append(mainFiles).append(" main, ").append(files.size() - mainFiles).append(" test), ")
                .append(lines).append(" lines\n")
                .append("- **Findings:** ").append(findings.size()).append(" total, ").append(findings.size() - open)
                .append(" resolved by documented waiver, ").append(open).append(" open (").append(blocking).append(" HIGH/MEDIUM)\n")
                .append("- **Verdict:** **").append(verdict).append("** (approval requires no open HIGH or MEDIUM finding)\n\n");

        md.append("## Rules applied\n\n| Rule | Severity | Scope | Check |\n|---|---|---|---|\n");
        for (Rule r : RULES) {
            md.append("| ").append(r.id()).append(" | ").append(r.severity()).append(" | ")
                    .append(r.mainOnly() ? "main" : "main + test").append(" | ").append(r.title()).append(" |\n");
        }
        md.append("\nCR-04 does not apply to files that declare a `main` method (CLI entry points).\n");

        md.append("\n## Findings\n\n");
        if (findings.isEmpty()) md.append("None.\n");
        else md.append("| Rule | Severity | Location | Status | Resolution |\n|---|---|---|---|---|\n");
        for (Finding x : findings) {
            md.append("| ").append(x.rule().id()).append(" | ").append(x.rule().severity()).append(" | `")
                    .append(x.file()).append(':').append(x.line()).append("` | ")
                    .append(x.open() ? "OPEN" : "ACCEPTED").append(" | ")
                    .append(x.open() ? x.rule().title() : x.waiver().replace("|", "/")).append(" |\n");
        }

        md.append("\n## Per-file results\n\n| File | Lines | Open | Accepted |\n|---|---|---|---|\n");
        for (SourceFile f : files) {
            long fo = findings.stream().filter(x -> x.file().equals(f.path()) && x.open()).count();
            long fa = findings.stream().filter(x -> x.file().equals(f.path()) && !x.open()).count();
            md.append("| `").append(f.path()).append("` | ").append(f.lines().size()).append(" | ")
                    .append(fo).append(" | ").append(fa).append(" |\n");
        }
        return new AgentResult(Map.of(OUTPUT, md.toString()),
                files.size() + " files reviewed, " + open + " open finding(s): " + verdict);
    }

    /** Applies every rule to one file. */
    static List<Finding> review(SourceFile f) {
        List<String> lines = f.lines();
        boolean cli = f.content().contains(CLI_MARKER);
        List<Finding> out = new ArrayList<>();
        for (Rule r : RULES) {
            if (r.mainOnly() && f.isTest()) continue;
            if (r.id().equals("CR-04") && cli) continue;
            if (r.id().equals("CR-02")) {
                Matcher m = r.pattern().matcher(f.content());
                while (m.find()) out.add(finding(r, f, lines, lineOf(f.content(), m.start())));
                continue;
            }
            for (int i = 0; i < lines.size(); i++) {
                if (!r.pattern().matcher(lines.get(i)).find()) continue;
                if (r.id().equals("CR-07") && hasJavadoc(lines, i)) continue;
                out.add(finding(r, f, lines, i + 1));
            }
        }
        return out;
    }

    private static Finding finding(Rule r, SourceFile f, List<String> lines, int line) {
        String waiver = null;
        for (int i = Math.max(0, line - 2); i < line; i++) {
            Matcher w = WAIVER.matcher(lines.get(i));
            if (w.find() && w.group(1).equals(r.id())) waiver = w.group(2);
        }
        return new Finding(r, f.path(), line, waiver);
    }

    /** Javadoc must end right above the declaration, ignoring annotations. */
    private static boolean hasJavadoc(List<String> lines, int declaration) {
        for (int i = declaration - 1; i >= 0; i--) {
            String l = lines.get(i).strip();
            if (l.startsWith("@")) continue;
            return l.endsWith("*/");
        }
        return false;
    }

    private static int lineOf(String content, int offset) {
        int line = 1;
        for (int i = 0; i < offset; i++) if (content.charAt(i) == '\n') line++;
        return line;
    }
}
