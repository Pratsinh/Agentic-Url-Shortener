package com.ascs.orchestrator.agents;

import com.ascs.orchestrator.core.Agent;
import com.ascs.orchestrator.model.AgentResult;
import com.ascs.orchestrator.model.StageInput;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Pattern;

/**
 * Development agent, version-control duties: audits the commit history against Conventional Commits and turns
 * the pending working-tree changes into a proposed series of scoped, meaningful commits (one per component),
 * so history stays reviewable. It proposes; a human (or the release gate) decides what is committed.
 */
public final class DevelopmentAgent implements Agent {

    public static final String OUTPUT = "development-report.md";
    static final Pattern CONVENTIONAL =
            Pattern.compile("^(feat|fix|docs|test|build|refactor|perf|chore|ci|style|revert)(\\([a-z0-9-]+\\))?!?: \\S.{8,}$");
    static final int MAX_SUBJECT = 72;

    private final CommandRunner git;

    public DevelopmentAgent(CommandRunner git) {
        this.git = git;
    }

    @Override
    public AgentResult execute(StageInput input) throws InterruptedException {
        StringBuilder md = new StringBuilder("# Development report\n\nGenerated by `DevelopmentAgent` from the git repository.\n\n");
        List<String> log;
        List<String> status;
        try {
            log = git.run(List.of("git", "log", "--format=%h%x09%s"));
            status = git.run(List.of("git", "status", "--porcelain", "--untracked-files=all"));
        } catch (IOException e) {
            md.append("Git is not available, so history and pending changes could not be assessed: ")
                    .append(e.getMessage()).append('\n');
            return new AgentResult(Map.of(OUTPUT, md.toString()), "git unavailable");
        }

        md.append("## 1. Commit history quality\n\n");
        int good = 0;
        StringBuilder rows = new StringBuilder("| Commit | Subject | Conventional | <= ").append(MAX_SUBJECT).append(" chars |\n|---|---|---|---|\n");
        for (String line : log) {
            String[] parts = line.split("\t", 2);
            String subject = parts.length > 1 ? parts[1] : "";
            boolean conventional = CONVENTIONAL.matcher(subject).matches();
            boolean shortEnough = subject.length() <= MAX_SUBJECT;
            if (conventional && shortEnough) good++;
            rows.append("| `").append(parts[0]).append("` | ").append(subject.replace("|", "/")).append(" | ")
                    .append(conventional ? "yes" : "**no**").append(" | ").append(shortEnough ? "yes" : "**no**").append(" |\n");
        }
        md.append(good).append(" of ").append(log.size()).append(" commits follow Conventional Commits with a subject of at most ")
                .append(MAX_SUBJECT).append(" characters.\n\n").append(log.isEmpty() ? "" : rows.toString()).append('\n');

        md.append("## 2. Proposed commits for pending changes\n\n");
        Map<String, List<String[]>> groups = new TreeMap<>();
        for (String line : status) {
            if (line.length() < 4) continue;
            String code = line.substring(0, 2).trim();
            String path = line.substring(3).replace("\"", "");
            groups.computeIfAbsent(group(path), k -> new ArrayList<>()).add(new String[]{code, path});
        }
        if (groups.isEmpty()) md.append("Working tree is clean: nothing to commit.\n");
        groups.forEach((scope, files) -> {
            md.append("```\n").append(message(scope, files)).append("\n```\n");
            files.forEach(f -> md.append("- `").append(f[0]).append("` ").append(f[1]).append('\n'));
            md.append('\n');
        });
        return new AgentResult(Map.of(OUTPUT, md.toString()),
                good + "/" + log.size() + " commits conventional; " + groups.size() + " commit(s) proposed");
    }

    /** "type(scope)" for a path: tests, docs and build files get their own commits; main code is grouped by component. */
    static String group(String modulePath) {
        String path = modulePath.replaceFirst("^[\\w.-]+/(?=src/)", ""); // orchestrator/src/main/java/... -> src/main/java/...
        if (path.startsWith("src/test/")) return "test(" + component(path.substring("src/test/java/".length())) + ")";
        if (path.startsWith("src/main/java/")) return "feat(" + component(path.substring("src/main/java/".length())) + ")";
        if (path.startsWith("docs/") || path.endsWith(".md")) return "docs";
        return "build";
    }

    private static String component(String javaPath) {
        String[] seg = javaPath.split("/");
        // com/ascs/<area>/<layer>/File.java -> area-layer ; com/ascs/<area>/File.java -> area ; com/ascs/File.java -> app
        if (seg.length >= 5) return seg[2] + "-" + seg[3];
        if (seg.length == 4) return seg[2];
        return "app";
    }

    static String message(String group, List<String[]> files) {
        List<String> added = new ArrayList<>();
        List<String> changed = new ArrayList<>();
        for (String[] f : files) {
            String name = f[1].substring(f[1].lastIndexOf('/') + 1).replaceFirst("\\.java$", "");
            (f[0].equals("??") || f[0].equals("A") ? added : changed).add(name);
        }
        boolean mainCode = group.startsWith("feat(");
        String type = mainCode && added.isEmpty() ? "refactor" + group.substring(4) : group;
        List<String> clauses = new ArrayList<>();
        if (!added.isEmpty()) clauses.add("add " + names(added));
        if (!changed.isEmpty()) clauses.add("update " + names(changed));
        String subject = type + ": " + String.join("; ", clauses);
        return subject.length() <= MAX_SUBJECT ? subject : subject.substring(0, MAX_SUBJECT - 3) + "...";
    }

    private static String names(List<String> names) {
        return names.size() <= 3 ? String.join(", ", names)
                : String.join(", ", names.subList(0, 3)) + " and " + (names.size() - 3) + " more";
    }
}
