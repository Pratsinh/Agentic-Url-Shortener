package com.ascs.orchestrator.agents;

import com.ascs.orchestrator.agents.StoryCatalog.Criterion;
import com.ascs.orchestrator.agents.StoryCatalog.Story;
import com.ascs.orchestrator.core.Agent;
import com.ascs.orchestrator.model.AgentResult;
import com.ascs.orchestrator.model.StageInput;

import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Pattern;

/**
 * Requirements agent: turns the requirement into user stories with Given/When/Then acceptance criteria.
 * Rule-based (catalog lookup), so it is deterministic and testable; an LLM-backed agent can replace it
 * behind the same {@link Agent} interface. Vague wording is surfaced as open questions, never guessed.
 */
public final class RequirementsAgent implements Agent {

    public static final String OUTPUT = "user-stories.md";
    private static final Pattern VAGUE = Pattern.compile("\\b(fast(er)?|secure|better|scalable|robust|easy|nice)\\b");

    @Override
    public AgentResult execute(StageInput input) {
        String requirement = input.requirement();
        List<Story> stories = StoryCatalog.select(requirement);

        StringBuilder md = new StringBuilder("# User stories and acceptance criteria\n\n")
                .append("**Requirement:** \"").append(requirement).append("\"\n\n")
                .append("Generated by `RequirementsAgent` from the product story catalog. Acceptance-criterion ids are ")
                .append("referenced by tests through `@Verifies` and traced by the QA agent.\n\n");

        var vague = VAGUE.matcher(requirement.toLowerCase(Locale.ROOT));
        StringBuilder questions = new StringBuilder();
        while (vague.find()) {
            questions.append("- \"").append(vague.group()).append("\" is not measurable: define a target metric.\n");
        }
        if (stories.isEmpty()) questions.append("- No known capability matches this requirement: a human must describe it.\n");
        if (!questions.isEmpty()) md.append("## Open questions\n\n").append(questions).append('\n');

        int criteria = 0;
        for (Story s : stories) {
            md.append("## ").append(s.id()).append(" ").append(s.title()).append("\n\n")
                    .append("**As a** ").append(s.role()).append(", **I want** ").append(s.goal())
                    .append(", **so that** ").append(s.benefit()).append(".\n\n")
                    .append("| AC | Given | When | Then |\n|---|---|---|---|\n");
            for (Criterion c : s.criteria()) {
                md.append("| ").append(c.id()).append(" | ").append(c.given()).append(" | ").append(c.when())
                        .append(" | ").append(c.then()).append(" |\n");
                criteria++;
            }
            md.append('\n');
        }
        return new AgentResult(Map.of(OUTPUT, md.toString()),
                stories.size() + " stories, " + criteria + " acceptance criteria");
    }
}
