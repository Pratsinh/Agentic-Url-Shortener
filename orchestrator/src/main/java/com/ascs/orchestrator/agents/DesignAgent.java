package com.ascs.orchestrator.agents;

import com.ascs.orchestrator.agents.StoryCatalog.Story;
import com.ascs.orchestrator.core.Agent;
import com.ascs.orchestrator.model.AgentResult;
import com.ascs.orchestrator.model.Artifact;
import com.ascs.orchestrator.model.StageInput;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Design agent: produces the design document from the stories and the real source tree. The component
 * diagram is derived from actual package references (so it cannot drift from the code), sequence diagrams
 * describe the main flows, and the documented layering rules are checked and reported as conformance.
 */
public final class DesignAgent implements Agent {

    public static final String OUTPUT = "design.md";
    private static final String ROOT = "com.ascs";
    private static final Pattern REF = Pattern.compile("\\bcom\\.ascs((?:\\.[a-z][a-z0-9]*)+)");
    private static final Pattern STORY = Pattern.compile("(?m)^## (US-\\d+) ");

    /** One architecture rule and the packages that break it. */
    public record Conformance(String rule, List<String> violations) {}

    private final Path projectRoot;

    public DesignAgent(Path projectRoot) {
        this.projectRoot = projectRoot;
    }

    @Override
    public AgentResult execute(StageInput input) {
        List<SourceFile> main = SourceFile.scan(projectRoot, SourceFile.sourceRoots(projectRoot, "main"));
        Map<String, Set<String>> deps = packageDependencies(main);
        List<Conformance> conformance = conformance(main, deps);
        long broken = conformance.stream().filter(c -> !c.violations().isEmpty()).count();

        StringBuilder md = new StringBuilder("# Design\n\n")
                .append("Generated by `DesignAgent` from the user stories and the source tree (")
                .append(main.size()).append(" main source files, ").append(deps.size()).append(" packages).\n\n");
        md.append("## 1. Context\n\n")
                .append("Two decoupled parts, built as separate modules with no compile dependency between them. The **URL shortener** ")
                .append("(`shortener-service`) is a microservice whose only public surface is its OpenAPI contract (`shortener-api`); ")
                .append("inside it is hexagonal: `domain` (rules) <- `app` (use cases and ports) <- `infra` (adapters) and `web` (Spring MVC). ")
                .append("The **orchestrator** (`orchestrator`, plain Java) drives role agents through a governed ")
                .append("SDLC graph: gates, policies, human approval before commit, retries, rollback, hash-chained audit.\n\n");
        md.append("## 2. Component diagram (derived from package references)\n\n```mermaid\n").append(mermaid(deps)).append("```\n\n");
        md.append("## 3. Main flows\n\n").append(SEQUENCES);
        md.append("## 4. Architecture conformance\n\n| Rule | Result |\n|---|---|\n");
        for (Conformance c : conformance) {
            md.append("| ").append(c.rule()).append(" | ")
                    .append(c.violations().isEmpty() ? "PASS" : "FAIL: " + String.join(", ", c.violations())).append(" |\n");
        }
        md.append("\n## 5. Traceability (story -> components)\n\n");
        List<String> ids = storyIds(input);
        if (ids.isEmpty()) md.append("No user stories were supplied upstream.\n");
        else md.append("| Story | Components |\n|---|---|\n");
        for (Story s : StoryCatalog.ALL) {
            if (!ids.contains(s.id())) continue;
            List<String> parts = s.components().stream()
                    .map(c -> deps.containsKey(c) ? "`" + c + "`" : "`" + c + "` (missing)").toList();
            md.append("| ").append(s.id()).append(" ").append(s.title()).append(" | ").append(String.join(", ", parts)).append(" |\n");
        }
        return new AgentResult(Map.of(OUTPUT, md.toString()),
                deps.size() + " packages diagrammed, " + broken + " architecture rule(s) violated");
    }

    /** package (relative to com.ascs) -> packages it references; every scanned package is a key. */
    static Map<String, Set<String>> packageDependencies(List<SourceFile> files) {
        Map<String, Set<String>> deps = new TreeMap<>();
        for (SourceFile f : files) {
            String pkg = shortName(f.packageName());
            Set<String> out = deps.computeIfAbsent(pkg, k -> new TreeSet<>());
            Matcher m = REF.matcher(f.content());
            while (m.find()) {
                String target = m.group(1).substring(1);
                if (!target.equals(pkg)) out.add(target);
            }
        }
        return deps;
    }

    static List<Conformance> conformance(List<SourceFile> files, Map<String, Set<String>> deps) {
        Set<String> springUsers = new TreeSet<>();
        for (SourceFile f : files) {
            String pkg = shortName(f.packageName());
            if (f.content().contains("import org." + "springframework") && !pkg.equals("shortener.web") && !pkg.equals(ROOT)) {
                springUsers.add(pkg);
            }
        }
        return List.of(
                new Conformance("Only `shortener.web` and the application class use Spring", List.copyOf(springUsers)),
                rule("`shortener.domain` depends on no other shortener package", deps,
                        p -> p.equals("shortener.domain"), t -> t.startsWith("shortener.")),
                rule("`shortener.app` depends only on `shortener.domain`", deps,
                        p -> p.equals("shortener.app"), t -> t.startsWith("shortener.") && !t.equals("shortener.domain")),
                rule("Orchestrator does not depend on the shortener", deps,
                        p -> p.startsWith("orchestrator"), t -> t.startsWith("shortener")),
                rule("Shortener does not depend on the orchestrator", deps,
                        p -> p.startsWith("shortener"), t -> t.startsWith("orchestrator")));
    }

    private static Conformance rule(String name, Map<String, Set<String>> deps,
                                    java.util.function.Predicate<String> from, java.util.function.Predicate<String> forbidden) {
        List<String> bad = new ArrayList<>();
        deps.forEach((pkg, targets) -> {
            if (from.test(pkg)) targets.stream().filter(forbidden).forEach(t -> bad.add(pkg + " -> " + t));
        });
        return new Conformance(name, bad);
    }

    static String mermaid(Map<String, Set<String>> deps) {
        StringBuilder sb = new StringBuilder("flowchart LR\n");
        for (String group : List.of("shortener", "orchestrator")) {
            sb.append("  subgraph ").append(group).append('\n');
            deps.keySet().stream().filter(p -> p.startsWith(group + "."))
                    .forEach(p -> sb.append("    ").append(node(p)).append("[").append(p).append("]\n"));
            sb.append("  end\n");
        }
        deps.forEach((pkg, targets) -> targets.forEach(t -> sb.append("  ").append(node(pkg)).append(" --> ").append(node(t)).append('\n')));
        return sb.toString();
    }

    private static String node(String pkg) {
        return pkg.replace('.', '_');
    }

    private static String shortName(String pkg) {
        return pkg.startsWith(ROOT + ".") ? pkg.substring(ROOT.length() + 1) : pkg;
    }

    private static List<String> storyIds(StageInput input) {
        List<String> ids = new ArrayList<>();
        input.artifact(RequirementsAgent.OUTPUT).map(Artifact::content).ifPresent(c -> {
            Matcher m = STORY.matcher(c);
            while (m.find()) ids.add(m.group(1));
        });
        return ids;
    }

    private static final String SEQUENCES = """
            ### Create a short link (US-1, US-5, US-6)

            ```mermaid
            sequenceDiagram
              participant C as Client
              participant F as RequestIdFilter
              participant W as ShortenerController
              participant S as ShortenerService
              participant V as UrlValidator
              participant R as LinkRepository
              participant A as AuditTrail
              C->>F: POST /api/v1/links
              F->>W: request (X-Request-Id in MDC)
              W->>S: create(url, ttl)
              S->>V: validate(url)
              loop up to 5 attempts
                S->>R: saveIfAbsent(candidate)
              end
              S->>A: LINK_CREATED (host only)
              W-->>C: 201 + Location (or RFC 7807 problem)
            ```

            ### Redirect (US-2, US-3, US-4)

            ```mermaid
            sequenceDiagram
              participant C as Visitor
              participant W as ShortenerController
              participant S as ShortenerService
              participant R as LinkRepository
              participant A as AuditTrail
              C->>W: GET /{code}
              W->>S: resolve(code)
              S->>R: find(code)
              alt unknown or expired
                S->>A: LINK_REDIRECT_REJECTED
                W-->>C: 404 / 410 problem
              else valid
                S->>R: recordClick(code, now)
                S->>A: LINK_REDIRECTED
                W-->>C: 302 Location
              end
            ```

            ### Governed delivery pipeline (US-7, US-8)

            ```mermaid
            flowchart LR
              requirements --> design --> development
              development --> code_review[code-review]
              development --> qa
              code_review --> release_readiness[release-readiness]
              qa --> release_readiness
              release_readiness -. human approval .-> commit[(artifact store)]
            ```

            """;
}
