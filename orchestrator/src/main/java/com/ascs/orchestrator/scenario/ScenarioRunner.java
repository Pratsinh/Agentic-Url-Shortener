package com.ascs.orchestrator.scenario;

import com.ascs.orchestrator.approval.ConsoleApprovalGateway;
import com.ascs.orchestrator.audit.AuditLog;
import com.ascs.orchestrator.model.RunReport;
import com.ascs.orchestrator.model.StageResult;
import com.ascs.orchestrator.planner.Task;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Set;

/**
 * Runs the three scenarios and renders a report from the REAL audit trail.
 * Usage: ScenarioRunner [projectRoot] [--out docs/SCENARIOS.md] [--interactive]
 */
public final class ScenarioRunner {
    private ScenarioRunner() {}


    private static final Set<AuditLog.Type> GOVERNANCE = Set.of(
            AuditLog.Type.PLAN_CREATED, AuditLog.Type.STAGE_ATTEMPT_FAILED, AuditLog.Type.STAGE_RETRY,
            AuditLog.Type.FALLBACK_USED, AuditLog.Type.POLICY_VIOLATION, AuditLog.Type.APPROVAL_REQUESTED,
            AuditLog.Type.APPROVAL_GRANTED, AuditLog.Type.APPROVAL_REJECTED, AuditLog.Type.APPROVAL_TIMED_OUT,
            AuditLog.Type.CHANGE_APPLIED, AuditLog.Type.REPLAN, AuditLog.Type.STAGE_INVALIDATED,
            AuditLog.Type.HALT_REQUESTED, AuditLog.Type.ROLLBACK_STARTED, AuditLog.Type.ROLLBACK_COMPLETED,
            AuditLog.Type.ROLLBACK_FAILED, AuditLog.Type.STAGE_FAILED, AuditLog.Type.STAGE_BLOCKED,
            AuditLog.Type.RUN_COMPLETED);

    public static void main(String[] args) throws IOException {
        Path root = Path.of(".");
        Path out = null;
        boolean interactive = false;
        for (int i = 0; i < args.length; i++) {
            if (args[i].equals("--out")) out = Path.of(args[++i]);
            else if (args[i].equals("--interactive")) interactive = true;
            else root = Path.of(args[i]);
        }
        Scenarios s = new Scenarios(root, interactive ? new ConsoleApprovalGateway() : null);
        List<Scenarios.Result> results = List.of(s.greenfield(), s.brownfield(), s.ambiguous());

        StringBuilder md = new StringBuilder("# Scenario runs\n\nGenerated by `ScenarioRunner` from real executions: "
                + "every table and event below comes from the engine's audit log and metrics, not from hand-written text.\n\n");
        int n = 1;
        for (Scenarios.Result r : results) {
            String section = render(n++, r);
            md.append(section).append('\n');
            System.out.println(section);
        }
        if (out != null) {
            if (out.getParent() != null) Files.createDirectories(out.getParent());
            Files.writeString(out, md.toString());
            System.out.println("wrote " + out);
        }
    }

    static String render(int number, Scenarios.Result r) {
        StringBuilder sb = new StringBuilder();
        sb.append("## Scenario ").append(number).append(": ").append(r.name()).append("\n\n");
        sb.append("**Requirement:** \"").append(r.requirement()).append("\"\n\n");

        sb.append("### 1. Requirement understanding\n\n");
        sb.append("- **Classification:** ").append(r.analysis().kind()).append('\n');
        sb.append("- **Engineering problem:** ").append(r.analysis().problemStatement()).append('\n');
        if (!r.analysis().ambiguities().isEmpty()) {
            sb.append("- **Ambiguities detected:**\n");
            r.analysis().ambiguities().forEach(a -> sb.append("  - ").append(a).append('\n'));
        }
        sb.append("- **Assumptions recorded:**\n");
        r.analysis().assumptions().forEach(a -> sb.append("  - ").append(a).append('\n'));

        sb.append("\n### 2. Decomposition and plan\n\n");
        sb.append("| Stage | Depends on | Output | Impact | Approval | Max attempts | Notes |\n|---|---|---|---|---|---|---|\n");
        for (Task t : r.analysis().tasks()) {
            String notes = String.join(", ", notes(t));
            sb.append("| ").append(t.id()).append(" | ").append(t.dependsOn().isEmpty() ? "-" : String.join(", ", t.dependsOn()))
                    .append(" | ").append(t.output()).append(" | ").append(t.impact()).append(" | ")
                    .append(t.requiresApproval() ? "yes" : "no").append(" | ").append(t.maxAttempts())
                    .append(" | ").append(notes.isEmpty() ? "" : notes).append(" |\n");
        }
        sb.append("\nParallel waves (stages in a wave can run concurrently; joins wait for all dependencies): `")
                .append(r.graph().levels()).append("`\n");

        sb.append("\n### 3. Orchestration and validation\n\n");
        for (RunReport run : r.runs()) {
            sb.append("**Run `").append(run.runId()).append("`  ->  ").append(run.outcome())
                    .append("** (").append(run.latency().toMillis()).append(" ms, replans=").append(run.replans()).append(")\n\n");
            sb.append("| Stage | Status | Attempts | Fallback | ms | Reason |\n|---|---|---|---|---|---|\n");
            for (StageResult st : run.stages()) {
                sb.append("| ").append(st.stageId()).append(" | ").append(st.status()).append(" | ").append(st.attempts())
                        .append(" | ").append(st.usedFallback() ? "yes" : "").append(" | ").append(st.duration().toMillis())
                        .append(" | ").append(trunc(st.reason(), 90)).append(" |\n");
            }
            sb.append('\n');
        }
        r.notes().forEach(x -> sb.append("- ").append(x).append('\n'));

        sb.append("\n**Governance and control events (from the audit log):**\n\n```\n");
        for (AuditLog.Event e : r.audit()) {
            if (!GOVERNANCE.contains(e.type())) continue;
            sb.append(String.format("#%03d %-20s %-18s %s%n", e.seq(), e.type(), e.stageId() == null ? "-" : e.stageId(),
                    trunc(e.detail(), 120)));
        }
        sb.append("```\n");

        sb.append("\n### 4. Reliability metrics\n\n```\n").append(r.metrics().format()).append("\n```\n");
        sb.append("\nAudit log: ").append(r.audit().size()).append(" events, hash chain ")
                .append(r.auditIntact() ? "**verified intact**" : "**BROKEN**").append(".\n");
        return sb.toString();
    }

    private static List<String> notes(Task t) {
        List<String> n = new java.util.ArrayList<>();
        if (t.compensable()) n.add("compensable");
        if (t.fallbackAgent() != null) n.add("fallback agent");
        if (t.onFailure() != com.ascs.orchestrator.model.FailureStrategy.BLOCK_DESCENDANTS) n.add("on failure: " + t.onFailure());
        return n;
    }

    private static String trunc(String s, int max) {
        String one = s == null ? "" : s.replace('\n', ' ').replace('|', '/');
        return one.length() <= max ? one : one.substring(0, max - 1) + "...";
    }
}
